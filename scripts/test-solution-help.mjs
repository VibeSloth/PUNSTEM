import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const c=vm.createContext({window:{PunstemLearning:{coach:()=> 'Keep accuracy before shortening the timer.'}}});
for(const file of ['chem-answers.js','solution-help.js'])vm.runInContext(fs.readFileSync('public/'+file,'utf8'),c);
const solve=c.window.PunstemHelp.solution;
const gibbs={q:'Find ΔG',topic:'Gibbs free energy',thermo:{deltaH:30,deltaS:290,temperatureK:298.15,temperatureC:25,mode:'gibbs'},method:'Use Kelvin and consistent units.',answer:{type:'number',value:-56.4635,display:'-56.464 kJ/mol'}};
const text=solve(gibbs,{input:'-86433.5'});
assert(text.includes('290 J/(mol·K) ÷ 1,000 = 0.29'));
assert(text.includes('30 − (298.15)(0.29)'));
assert(text.includes('25 + 273.15'));
assert(text.includes('For you:'));
const inverse=solve({kind:'inverseRule',fields:[],explain:'Answer: (4*x+3)/(2-x)'});
assert(inverse.includes('multiply both sides by its denominator'));
assert(inverse.includes('original range'));
const graph=solve({points:[{x:1,y:3},{x:2,y:5}]},{points:[{x:1,y:3}]});
assert(/\(1, 3\).*you placed this correctly/.test(graph));
assert(graph.includes('(2, 5)'));
console.log('Solution feedback checks passed: worked Gibbs setup, inverse steps, graph point comparison, and personal coaching.');
